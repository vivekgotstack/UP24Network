export function hindiPublication(document: PublicationDocument): PublicationDocument | undefined {
  const edition = editions[document.path];
  if (!edition) return undefined;
  return {
    ...document,
    label: edition.label,
    title: edition.title,
    description: edition.description,
    intro: edition.intro,
    sections: document.sections.map((section) => {
      const { id, links, points } = section;
      if (!edition.sections[id]) return section;
      const [title, ...paragraphs] = edition.sections[id];
      return {
        id,
        title,
        paragraphs,
        ...(points && id === 'news-tips'
          ? {
              points: [
                'जगह, तारीख और घटना का संक्षिप्त विवरण दें।',
                'जाँचे जा सकने वाले सार्वजनिक रिकॉर्ड या अन्य प्रमाण बताएँ।',
                'आगे बात के लिए निजी संपर्क का तरीका दें।',
              ],
            }
          : {}),
        ...(links
          ? {
              links: links.map(({ href, label }) => ({
                href,
                label: editions[href]?.label ?? label,
              })),
            }
          : {}),
      };
    }),
  };
}
